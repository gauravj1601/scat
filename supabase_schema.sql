-- Run in the Supabase SQL editor if you want persistent cloud storage.
-- ONLY the Streamlit server holds SUPABASE_SERVICE_KEY. Never put it in a client.
CREATE TABLE IF NOT EXISTS public.omr_results (
    id bigint generated by default as identity primary key,
    submitted_at timestamptz NOT NULL default now(),
    image_hash text NOT NULL UNIQUE,
    exam_date date NOT NULL,
    exam_type text NOT NULL,
    class_name text NOT NULL,
    paper_code text NOT NULL,
    paper_version text NOT NULL,
    roll_number text NOT NULL,
    student_name text NOT NULL,
    total numeric NOT NULL,
    maximum numeric NOT NULL,
    verification_status text NOT NULL,
    payload jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS public.omr_answer_keys (
    key_id text primary key,
    csv_text text NOT NULL,
    saved_at timestamptz NOT NULL default now()
);
ALTER TABLE public.omr_results ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.omr_answer_keys ENABLE ROW LEVEL SECURITY;
-- No public policies. Only a server-held Supabase service key can read or write.
